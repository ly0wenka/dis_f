# Створення презентації
prs = Presentation()
prs.slide_width = Inches(13.333)
prs.slide_height = Inches(7.5)

def add_title_slide(prs, title, subtitle=""):
    slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(slide_layout)
    slide.shapes.title.text = title
    if subtitle:
        slide.placeholders[1].text = subtitle

def add_content_slide(prs, title, content_lines, bullet=True):
    slide_layout = prs.slide_layouts[1]
    slide = prs.slides.add_slide(slide_layout)
    slide.shapes.title.text = title
    body = slide.placeholders[1]
    tf = body.text_frame
    tf.text = content_lines[0] if content_lines else ""
    for line in content_lines[1:]:
        p = tf.add_paragraph()
        p.text = line
        if bullet:
            p.level = 0
            p.bullet = True

def add_table_slide(prs, title, headers, rows):
    slide_layout = prs.slide_layouts[5]
    slide = prs.slides.add_slide(slide_layout)
    slide.shapes.title.text = title
    left = Inches(0.5)
    top = Inches(1.5)
    width = Inches(12)
    height = Inches(5)
    table = slide.shapes.add_table(len(rows)+1, len(headers), left, top, width, height).table
    for col, header in enumerate(headers):
        cell = table.cell(0, col)
        cell.text = header
        cell.text_frame.paragraphs[0].font.bold = True
    for row_idx, row in enumerate(rows):
        for col_idx, val in enumerate(row):
            table.cell(row_idx+1, col_idx).text = str(val)

def add_slide_with_image_placeholder(prs, title, text_lines, figure_ref):
    slide_layout = prs.slide_layouts[1]
    slide = prs.slides.add_slide(slide_layout)
    slide.shapes.title.text = title
    body = slide.placeholders[1]
    tf = body.text_frame
    tf.text = text_lines[0] if text_lines else ""
    for line in text_lines[1:]:
        p = tf.add_paragraph()
        p.text = line
        p.bullet = True
    left = Inches(8.5)
    top = Inches(2.5)
    width = Inches(4)
    height = Inches(4)
    textbox = slide.shapes.add_textbox(left, top, width, height)
    text_frame = textbox.text_frame
    text_frame.word_wrap = True
    p = text_frame.add_paragraph()
    p.text = f"▶ ТУТ МАЄ БУТИ РИСУНОК: {figure_ref}"
    p.font.size = Pt(12)
    p.font.color.rgb = RGBColor(128, 128, 128)

